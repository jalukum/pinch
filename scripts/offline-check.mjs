import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const p = await b.newPage()
await p.goto('http://localhost:4173/pinch/', { waitUntil: 'networkidle0' })
await p.evaluate(() => navigator.serviceWorker.ready)
await p.reload({ waitUntil: 'networkidle0' })
await p.type('#paste-input', 'https://www.bbcgoodfood.com/recipes/easy-pancakes'); await p.click('.go-btn')
await p.waitForSelector('.stamp-btn', { timeout: 60000 }); await p.click('.stamp-btn')
await new Promise(r => setTimeout(r, 6000))
const cards = await p.evaluate(() => new Promise(r => { const q = indexedDB.open('pinch'); q.onsuccess = () => { const t = q.result.transaction('recipes').objectStore('recipes').getAll(); t.onsuccess = () => r(t.result.map(x => ({ id: x.id, t: x.title, img: (x.imageData || '').slice(0, 22), len: (x.imageData||'').length }))) } }))
console.log(cards)
await p.setOfflineMode(true)
await p.goto('http://localhost:4173/pinch/#/r/' + cards[0].id, { waitUntil: 'load' })
await new Promise(r => setTimeout(r, 1500))
console.log('offline title:', await p.$eval('#recipe-title', e => e.textContent).catch(e => 'FAIL ' + e.message))
console.log('offline img loaded:', await p.$eval('.recipe img', i => i.complete && i.naturalWidth).catch(() => 'none'))
await b.close()
